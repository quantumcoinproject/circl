func TestExpandSeedDeterministic(t *testing.T) {
	var baseSeed [BaseSeedSize]byte
	for i := range baseSeed {
		baseSeed[i] = byte(i)
	}

	got, err := ExpandSeed(baseSeed)
	if err != nil {
		t.Fatalf("ExpandSeed returned error: %v", err)
	}

	expected := [SeedSize]byte{
		50, 9, 73, 15, 237, 77, 113, 201, 5, 175, 39, 232, 53, 173, 169, 157,
		61, 94, 83, 184, 176, 178, 8, 35, 123, 226, 167, 164, 0, 84, 224, 133,
		168, 179, 143, 152, 19, 247, 251, 76, 214, 227, 248, 141, 113, 92, 174, 123,
		22, 98, 203, 150, 70, 19, 250, 240, 85, 173, 149, 144, 152, 207, 248, 130,
		85, 230, 164, 224, 241, 151, 35, 24, 156, 6, 86, 237, 174, 223, 68, 220,
		17, 173, 93, 0, 162, 0, 154, 120, 203, 73, 160, 122, 238, 157, 46, 242,
		228, 231, 99, 222, 244, 186, 101, 173, 195, 226, 37, 44, 99, 87, 160, 59,
		58, 237, 64, 204, 218, 187, 155, 241, 108, 139, 75, 240, 97, 17, 160, 246,
		42, 211, 203, 166, 11, 158, 254, 157, 29, 83, 184, 103, 89, 224, 254, 157,
		157, 167, 103, 141, 127, 17, 244, 190, 48, 27, 128, 179, 246, 62, 241, 98,
	}
	if got != expected {
		t.Fatalf("expanded seed mismatch: got=%v", got)
	}
}
