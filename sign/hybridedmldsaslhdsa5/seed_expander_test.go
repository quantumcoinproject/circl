func TestExpandSeedDeterministic(t *testing.T) {
	var baseSeed [BaseSeedSize]byte
	for i := range baseSeed {
		baseSeed[i] = byte(i)
	}

	got, err := ExpandSeed(baseSeed)
	if err != nil {
		t.Fatalf("ExpandSeed returned error: %v", err)
	}

	expected := [SeedSize]byte{
		189, 220, 47, 255, 138, 92, 203, 227, 80, 19, 101, 86, 105, 93, 86, 77,
		52, 240, 114, 97, 38, 195, 14, 134, 180, 180, 157, 24, 40, 230, 231, 30,
		84, 154, 189, 19, 95, 189, 177, 179, 170, 74, 228, 168, 151, 131, 210, 171,
		133, 56, 133, 42, 127, 10, 233, 213, 123, 227, 218, 117, 197, 183, 36, 155,
		205, 248, 73, 223, 176, 234, 97, 124, 59, 202, 249, 177, 65, 237, 29, 235,
		111, 136, 250, 215, 239, 104, 202, 76, 106, 255, 191, 250, 128, 167, 108, 74,
		241, 36, 189, 61, 99, 241, 163, 200, 10, 209, 131, 47, 145, 211, 26, 98,
		21, 68, 30, 96, 184, 176, 241, 55, 52, 214, 237, 235, 23, 108, 203, 120,
		56, 183, 105, 134, 93, 10, 128, 252, 159, 30, 193, 183, 179, 106, 76, 107,
		17, 236, 230, 102, 21, 21, 154, 68, 44, 8, 50, 215, 14, 14, 50, 128,
	}
	if got != expected {
		t.Fatalf("expanded seed mismatch: got=%v", got)
	}
}
